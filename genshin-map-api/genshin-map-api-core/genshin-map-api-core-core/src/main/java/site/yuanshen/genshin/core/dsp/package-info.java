/**
 * DSP —— Data Shield Protection（数据防护）。
 *
 * <p>它把「直接爬 CDN 资源」变成「先取得一张有时效的票」：票据以三个 Cookie（Base / Sign /
 * Payload）随登录响应下发，由 CDN 边缘函数即时验证，边缘再把校验结论签名回调本服务复核。
 *
 * <p>分三层，切法是「谁和谁必须逐字节一致」，不是「谁是什么类型」：
 * <ul>
 *   <li>{@code protocol} —— 签发端、边缘、校验段三边必须一致的部分：协议常量与待签串、
 *       payload 编解码、HMAC 算法。改这里等于改协议，三边必须同改。</li>
 *   <li>{@code issue} —— 签发端：把票据写成 Set-Cookie，挂在登录响应上。</li>
 *   <li>{@code verify} —— 校验端（本层尚未落地）：接收边缘回调、验第二段签名，回答
 *       「这张票现在能不能取资源」—— 一档结论，放行或拒绝，不按请求路径做范围判定。</li>
 * </ul>
 *
 * <p>「哪些请求需要验票」不在这套代码里：它由 CDN 侧的路径规则决定，CDN 只把需要保护的那部分
 * 路径接到边缘函数上。所以协议里没有路径、没有资源范围，请求路径也不进待签串 —— 加一条受保护
 * 路径是一次 CDN 配置变更，不改代码，也不存在「签发端与边缘对同一条路径理解不一致」这个面。
 * 代价是一张票在有效期内对所有受保护路径都有效，票据与路径是解耦的。
 *
 * <p>票据只承载 uid 与 exp，不承载权限：封禁、登出、权限变更这类「当前状态」由校验段在每次
 * 回调时现判 —— 写进票据就得等它过期才能生效，而复制一张票也会把权限一起带走。
 */
